import type { ReactNode, SVGProps } from 'react';

import styles from './icon.module.scss';

export interface PaymentMarkProps extends Omit<
  SVGProps<SVGSVGElement>,
  'children' | 'width' | 'height' | 'viewBox'
> {
  // The card system's name, read by assistive technology; the mark is never decorative.
  title: string;
}

// Lamoda's grey card marks (a.lmcdn.ru bs2/5/86/visa.svg, bs2/7/78/mastercard.svg) at the size they
// were drawn. Unlike the icons they are not square and keep Lamoda's colours (greys, and
// Mastercard's orange ™): they are pictures, so their fills are not tokens.
function createPaymentMark(displayName: string, width: number, height: number, art: ReactNode) {
  function PaymentMark({ title, className, ...props }: PaymentMarkProps) {
    return (
      <svg
        xmlns="http://www.w3.org/2000/svg"
        width={width}
        height={height}
        viewBox={`0 0 ${width} ${height}`}
        fill="none"
        role="img"
        aria-label={title}
        className={className ? `${styles.icon} ${className}` : styles.icon}
        {...props}
      >
        <title>{title}</title>
        {art}
      </svg>
    );
  }
  PaymentMark.displayName = displayName;
  return PaymentMark;
}

